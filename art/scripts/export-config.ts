// Writes art-config.json from src/config.ts, shapes.ts, biomes.ts and slab.ts, for tools that can't
// import TypeScript. Run: npm run config (Node 22+). The TypeScript files stay the source of truth.

import { writeFileSync } from 'node:fs';
import { ART, FONT_BODY, FONT_DISPLAY, GUIDE_TINT, INK, INK_SOFT, PAPER, SIGNAL } from '../src/config.ts';
import { ART_SHAPES, BOULDER_DIAMETER } from '../src/shapes.ts';
import { BIOMES } from '../src/biomes.ts';
import { SLAB_DEPTH, pedestalHeight } from '../src/slab.ts';
import { BUNTING_KEYS, CHECKPOINT } from '../src/checkpoint.ts';
import { STAR_LAYERS } from '../src/stars.ts';
import { POWER, POWER_COLORS } from '../src/powers.ts';
import { COSMOS_PALETTES, LANDMARKS } from '../src/cosmos.ts';
import { BADGE_TIERS, TITLES } from '../src/ui/badge.ts';
import { UI_ICONS } from '../src/ui/icons.ts';
import { UNLOCKS } from '../src/ui/screens.ts';

const out = {
  $comment: 'Generated by art/scripts/export-config.ts from art/src. Edit the TypeScript, not this file.',
  colors: { ink: INK, inkSoft: INK_SOFT, paper: PAPER, signal: SIGNAL, guideTint: GUIDE_TINT },
  fonts: { display: FONT_DISPLAY, body: FONT_BODY },
  art: ART,
  shapes: Object.values(ART_SHAPES).map(s => ({
    key: s.key, name: s.name, tier: s.tier, light: s.light, base: s.base, shade: s.shade,
    material: s.material ?? null, cells: s.cells ?? null, custom: s.custom ?? null,
  })),
  boulderDiameter: BOULDER_DIAMETER,
  biomes: BIOMES,
  foundation: { slabDepth: SLAB_DEPTH, pedestalHeight: pedestalHeight() },
  checkpoint: { ...CHECKPOINT, bunting: BUNTING_KEYS },
  stars: STAR_LAYERS,
  powers: { ...POWER, colors: POWER_COLORS },
  cosmos: { palettes: COSMOS_PALETTES, landmarks: LANDMARKS.map(l => ({ name: l.name, dur: l.dur })), checkpointsPerPalette: 6 },
  ui: { badgeTiers: BADGE_TIERS, titles: TITLES, unlocks: UNLOCKS, icons: UI_ICONS },
};

const path = new URL('../art-config.json', import.meta.url);
writeFileSync(path, JSON.stringify(out, null, 2) + '\n');
console.log('wrote', path.pathname);
